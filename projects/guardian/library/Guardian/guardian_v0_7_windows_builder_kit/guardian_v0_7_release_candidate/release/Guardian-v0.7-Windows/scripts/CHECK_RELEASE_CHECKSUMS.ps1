$ErrorActionPreference = "Stop"
$Release = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
$ChecksumFile = Join-Path $Release "RELEASE_CHECKSUMS.txt"

if (-not (Test-Path $ChecksumFile)) {
    Write-Error "RELEASE_CHECKSUMS.txt does not exist. It is generated by BUILD_WINDOWS.ps1."
    exit 10
}

$Failures = @()
foreach ($Line in Get-Content $ChecksumFile) {
    if ([string]::IsNullOrWhiteSpace($Line)) { continue }
    $Parts = $Line -split "\s{2,}", 2
    if ($Parts.Count -ne 2) {
        $Failures += "Malformed checksum line: $Line"
        continue
    }
    $Expected = $Parts[0].Trim().ToLowerInvariant()
    $Relative = $Parts[1].Trim()
    $Path = Join-Path $Release $Relative
    if (-not (Test-Path $Path)) {
        $Failures += "Missing: $Relative"
        continue
    }
    $Actual = (Get-FileHash -Algorithm SHA256 $Path).Hash.ToLowerInvariant()
    if ($Actual -ne $Expected) {
        $Failures += "Mismatch: $Relative"
    }
}

if ($Failures.Count -gt 0) {
    Write-Host "Release checksum verification FAILED." -ForegroundColor Red
    $Failures | ForEach-Object { Write-Host "- $_" }
    exit 1
}

Write-Host "Release checksum verification PASSED." -ForegroundColor Green
exit 0
