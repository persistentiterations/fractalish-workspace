#!/usr/bin/env python3
"""
One-click local arena loop v0.1 — materializer → PlayableState → hotseat.

Usage:
  python run_arena_v0_1.py
  python run_arena_v0_1.py path/to/program.symlan
  python run_arena_v0_1.py --no-open
  python run_arena_v0_1.py --seed my-seed examples/….symlan

Writes companions next to the hotseat surface:
  last_playable_state.json   — canonical PlayableState
  last_playable_state.js     — window.__LAST_PLAYABLE_STATE__ for file:// hotseat

Play-dir resolution: prefers sibling ../05_play_surfaces/ (teaching-package layout);
falls back to this script's directory. Opens hotseat in the browser unless --no-open.

Claim boundary: local prototype loop only. Not an IDE, not a full compiler,
not production, not networking. HAL geometry/gates unchanged.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys
import webbrowser

# Runtime dir (materializer lives here). Play surface may be sibling 05_play_surfaces/.
ROOT = pathlib.Path(__file__).resolve().parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from materializer_v0_1 import (  # noqa: E402
    EXAMPLE_PROGRAM,
    PROFILE_ATTRACTOR,
    PROFILE_PROJECTED,
    canonical_json,
    materialize,
    sha256_hex,
)


def _resolve_play_dir() -> pathlib.Path:
    """Prefer package layout 05_play_surfaces/ next to 04_runtime/; else same dir as this script."""
    sibling = ROOT.parent / "05_play_surfaces"
    if sibling.is_dir() and (sibling / "hotseat_play_surface_v0_1.html").is_file():
        return sibling
    return ROOT


PLAY_DIR = _resolve_play_dir()
OUT_JSON = PLAY_DIR / "last_playable_state.json"
OUT_JS = PLAY_DIR / "last_playable_state.js"
HOTSEAT = PLAY_DIR / "hotseat_play_surface_v0_1.html"


def _compact_for_hotseat(state: dict) -> dict:
    """Drop dense edge list; hotseat uses orthogonal4 + gate rules (same as embed)."""
    s = json.loads(canonical_json(state))  # deep copy via round-trip
    # Attractor-graph states are not hotseat board surfaces; write as-is.
    if s.get("hal_profile", "").endswith("attractor_graph.v0.1"):
        return s
    nav = dict(s.get("navigability") or {})
    nav["edges"] = []
    nav["note"] = (
        "edges omitted by run_arena_v0_1; client uses orthogonal4 + gate rules"
    )
    s["navigability"] = nav
    return s


def write_outputs(state: dict) -> str:
    """Write JSON + JS companion; return SHA-256 of canonical JSON bytes."""
    compact = _compact_for_hotseat(state)
    text = canonical_json(compact)
    digest = sha256_hex(text)

    OUT_JSON.write_text(text + "\n", encoding="utf-8")

    # file://-safe companion: hotseat reads window.__LAST_PLAYABLE_STATE__
    js = (
        "/* Generated by run_arena_v0_1.py — do not edit by hand */\n"
        "window.__LAST_PLAYABLE_STATE__ = "
        + text
        + ";\n"
    )
    OUT_JS.write_text(js, encoding="utf-8")
    return digest


def load_source(path: pathlib.Path | None) -> tuple[str, str]:
    """Return (source_text, label)."""
    if path is None:
        return EXAMPLE_PROGRAM, "materializer §7 EXAMPLE_PROGRAM"
    path = path.resolve()
    if not path.is_file():
        raise FileNotFoundError(f"source not found: {path}")
    return path.read_text(encoding="utf-8"), str(path)


def open_hotseat() -> str:
    """Open hotseat in default browser; return file:// URL."""
    if not HOTSEAT.is_file():
        raise FileNotFoundError(f"hotseat not found: {HOTSEAT}")
    url = HOTSEAT.resolve().as_uri()
    # Prefer last materializer output when present
    url_with_flag = url + "?load=last"
    webbrowser.open(url_with_flag)
    return url_with_flag


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(
        description="Materialize SymLan teaching program → hotseat PlayableState (local only)."
    )
    p.add_argument(
        "source",
        nargs="?",
        default=None,
        help="Optional .symlan path (default: HAL §7 example embedded in materializer)",
    )
    p.add_argument(
        "--seed",
        default=None,
        help="Override discovery seed (default: seed from source or materializer)",
    )
    p.add_argument(
        "--profile",
        default=PROFILE_PROJECTED,
        choices=[PROFILE_PROJECTED, PROFILE_ATTRACTOR],
        help=f"HAL geometry profile (default: {PROFILE_PROJECTED})",
    )
    p.add_argument(
        "--no-open",
        action="store_true",
        help="Do not open the browser; only write JSON/JS",
    )
    args = p.parse_args(argv)

    try:
        src_path = pathlib.Path(args.source) if args.source else None
        source, label = load_source(src_path)
    except OSError as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 2

    print("=== SymLan arena loop v0.1 (local) ===")
    print(f"source:     {label}")
    print(f"profile:    {args.profile}")
    print(f"seed:       {args.seed if args.seed is not None else '(from program / default)'}")

    try:
        state = materialize(source, seed=args.seed, profile=args.profile)
    except Exception as e:
        print(f"ERROR materialize failed: {e}", file=sys.stderr)
        print(
            "Note: materializer_v0_1 accepts the teaching subset "
            "(node, coupling, vocab, run discovery, after resolve, send, expect, branch on T).",
            file=sys.stderr,
        )
        return 1

    digest = write_outputs(state)

    # Projected schema uses clock.turn_node; attractor schema uses clock.turn_actor.
    clock = state.get("clock") or {}
    turn = clock.get("turn_node") or clock.get("turn_actor") or "—"

    print(f"PlayableState → {OUT_JSON}")
    print(f"JS companion  → {OUT_JS}")
    print(f"SHA-256 (canonical JSON): {digest}")
    print(
        f"gate={state['gate']['outcome']}  S={state['slice']['S']}  "
        f"V={state['vocabulary']['status']}  turn={turn}"
    )
    print(f"hotseat:      {HOTSEAT}")
    print(f"play_dir:     {PLAY_DIR}")

    if args.profile == PROFILE_ATTRACTOR:
        print(
            "Note: hotseat v0.1 is projected_3space-only; attractor JSON written for inspect, "
            "not board play."
        )
        if not args.no_open:
            print("Skipping browser open for attractor_graph (use --no-open to silence).")
        return 0

    if args.no_open:
        print("Browser not opened (--no-open).")
        print(f"Open manually: {HOTSEAT.resolve().as_uri()}?load=last")
        print("Or: python -m http.server 8765   then  http://127.0.0.1:8765/hotseat_play_surface_v0_1.html?load=last")
        return 0

    try:
        url = open_hotseat()
        print(f"Opened:       {url}")
    except Exception as e:
        print(f"Could not auto-open browser: {e}", file=sys.stderr)
        print(f"Open manually: {HOTSEAT.resolve().as_uri()}?load=last")
        return 0

    print("Claim boundary: local prototype loop only — not production, not online.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
